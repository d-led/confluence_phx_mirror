// Include phoenix_html to handle method=PUT/DELETE in forms and buttons.
import "phoenix_html";
// Establish Phoenix Socket and LiveView configuration.
import { Socket } from "phoenix";
import { LiveSocket } from "phoenix_live_view";
import { hooks as colocatedHooks } from "phoenix-colocated/confluence_phx_mirror";
import topbar from "../vendor/topbar";
import { highlightCode } from "./code_highlight";
import { localizeTimes } from "./local_time";
import "./confirm";
import "./sidebar";
import "./heading_anchors";
import "./page_tree";
import "./topbar_menus";

const csrfToken = document
  .querySelector("meta[name='csrf-token']")
  .getAttribute("content");
const liveSocket = new LiveSocket("/live", Socket, {
  longPollFallbackMs: 2500,
  params: { _csrf_token: csrfToken },
  hooks: { ...colocatedHooks },
  // A patch re-renders the server's UTC text, so put the reader's zone back.
  dom: { onPatchEnd: (container) => localizeTimes(container) },
});

// Show progress bar on live navigation and form submits
topbar.config({ barColors: { 0: "#29d" }, shadowColor: "rgba(0, 0, 0, .3)" });
window.addEventListener("phx:page-loading-start", (_info) => topbar.show(300));
window.addEventListener("phx:page-loading-stop", (_info) => topbar.hide());

// A plain link is a whole page load, and the browser paints nothing between the
// click and the response: on a slow page that gap reads as "the click did not
// work". The same bar, shown only if the wait is noticeable.
document.addEventListener("click", (event) => {
  const modified =
    event.defaultPrevented ||
    event.button !== 0 ||
    event.metaKey ||
    event.ctrlKey ||
    event.shiftKey ||
    event.altKey;
  if (modified) return;

  const link = event.target.closest("a[href]");
  if (!link || link.target || link.hasAttribute("download")) return;
  if (link.origin !== window.location.origin) return;
  if (link.getAttribute("href").startsWith("#")) return;

  topbar.show(120);
});

window.addEventListener("pageshow", () => topbar.hide());

// connect if there are any LiveViews on the page
liveSocket.connect();

// Colour the code inside Confluence's code macro after the page is parsed.
highlightCode();

// Timestamps arrive as UTC; show them on the reader's clock.
localizeTimes();

// expose liveSocket on window for web console debug logs and latency simulation:
// >> liveSocket.enableDebug()
// >> liveSocket.enableLatencySim(1000)  // enabled for duration of browser session
// >> liveSocket.disableLatencySim()
window.liveSocket = liveSocket;

// The lines below enable quality of life phoenix_live_reload
// development features:
//
//     1. stream server logs to the browser console
//     2. click on elements to jump to their definitions in your code editor
//
if (process.env.NODE_ENV === "development") {
  window.addEventListener(
    "phx:live_reload:attached",
    ({ detail: reloader }) => {
      // Enable server log streaming to client.
      // Disable with reloader.disableServerLogs()
      reloader.enableServerLogs();

      // Open configured PLUG_EDITOR at file:line of the clicked element's HEEx component
      //
      //   * click with "c" key pressed to open at caller location
      //   * click with "d" key pressed to open at function component definition location
      let keyDown;
      window.addEventListener("keydown", (e) => (keyDown = e.key));
      window.addEventListener("keyup", (_e) => (keyDown = null));
      window.addEventListener(
        "click",
        (e) => {
          if (keyDown === "c") {
            e.preventDefault();
            e.stopImmediatePropagation();
            reloader.openEditorAtCaller(e.target);
          } else if (keyDown === "d") {
            e.preventDefault();
            e.stopImmediatePropagation();
            reloader.openEditorAtDef(e.target);
          }
        },
        true,
      );

      window.liveReloader = reloader;
    },
  );
}
